import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const base='http://127.0.0.1:8765/';
const browser=await chromium.launch({headless:true,args:['--enable-webgl','--use-gl=angle','--use-angle=swiftshader']});
const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,acceptDownloads:true});
const pageErrors=[];
page.on('pageerror',e=>pageErrors.push(e.message));
try{
 await page.goto(base,{waitUntil:'domcontentloaded'});
 await page.locator('[data-a="newphoto"]').click();
 await page.locator('a[href$="/studio"]').click();
 await page.getByRole('heading',{name:'Design to Purchase'}).waitFor();
 const set=async(key,value)=>{
  const input=page.locator('[data-v17-key="'+key+'"]');
  await input.fill(String(value));await input.dispatchEvent('change');
 };
 await set('width',30);await set('depth',20);await set('height',8);
 await page.locator('#v17-preview canvas').waitFor({timeout:20000});
 await page.locator('[data-v17-key="doorWidthIn"]').fill('90');
 await page.locator('[data-v17-key="doorWidthIn"]').dispatchEvent('change');
 await page.getByText('Door needs adjustment:').waitFor();
 await page.locator('[data-v17-key="doorWidthIn"]').fill('36');
 await page.locator('[data-v17-key="doorWidthIn"]').dispatchEvent('change');
 await page.locator('[data-v17-key="doorBay"]').selectOption('1');
 await page.locator('[data-v17-key="doorHinge"]').selectOption('right');
 await page.locator('[data-v17-key="doorHinge"]').selectOption('left');
 await page.locator('[data-v17-key="doorOpen"]').check();
 await page.locator('#v17-preview canvas').waitFor({timeout:20000});
 await page.screenshot({path:'qa-v17-mobile-design.png',fullPage:true});
 await page.locator('[data-v17-tab="docs"]').click();
 await page.getByText('01 Engineering & Plans').waitFor();
 const pdfPromise=page.waitForEvent('download');
 await page.locator('[data-v17-action="pdf"]').click();
 const pdf=await pdfPromise;
 assert.match(pdf.suggestedFilename(),/Concept-Drawings.*\.pdf$/);
 await page.locator('[data-v17-tab="buy"]').click();
 assert.match(await page.locator('.v17-pill').innerText(),/DRAFT/);
 await page.locator('[data-v17-tab="design"]').click();
 await page.locator('[data-v17-key="verified"]').check();
 await page.locator('[data-v17-tab="buy"]').click();
 page.once('dialog',async dialog=>dialog.accept());
 await page.locator('[data-v17-action="approve"]').click();
 await page.locator('.v17-pill.v17-success').waitFor();
 const csvPromise=page.waitForEvent('download');
 await page.locator('[data-v17-action="csv"]').click();
 const csv=await csvPromise;
 assert.match(csv.suggestedFilename(),/Cutting-Plan.*\.csv$/);
 await page.locator('[data-v17-tab="design"]').click();
 await set('width',31);
 await page.locator('[data-v17-tab="buy"]').click();
 await page.locator('.v17-pill.v17-warning').waitFor();
 await page.goto(base);
 await page.locator('[data-a="demo"]').click();
 await page.locator('a[href$="/studio"]').click();
 await page.locator('[data-v17-tab="match"]').click();
 await page.locator('.v17-compare .v17-after').waitFor({timeout:20000});
 await page.screenshot({path:'qa-v17-mobile-photomatch.png',fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+5),true,'No horizontal scrolling on mobile');
 assert.deepEqual(pageErrors,[],'No browser JavaScript errors: '+JSON.stringify(pageErrors));
 console.log('PASS V17 mobile: navigation, WebGL, plans PDF, CSV, purchase approval, invalidation, real before/after photos');
}finally{await browser.close();}
