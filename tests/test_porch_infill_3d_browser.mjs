import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,args:['--enable-webgl','--use-gl=angle','--use-angle=swiftshader']});
const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto('http://127.0.0.1:8765/',{waitUntil:'domcontentloaded'});
 await page.locator('[data-a="demo"]').click();
 await page.locator('a[href$="/studio"]').click();
 await page.locator('[data-v17-tab="trace"]').click();
 await page.locator('[data-trace-start]').click();
 const stage=page.locator('#v17-porch-infill-3d');
 await stage.locator('canvas').waitFor({timeout:20000});
 assert.equal(await stage.getAttribute('data-preview-mode'),'porch-infill');
 assert.equal(await stage.getAttribute('data-arch-count'),'3');
 assert.equal(await stage.getAttribute('data-roof-added'),'false');
 assert.equal(await stage.getAttribute('data-takeoff-eligible'),'false');
 assert.equal(await stage.getAttribute('data-doors'),'0','No door is invented before selection');
 await page.locator('[data-trace-door]').selectOption('arch-2');
 await stage.locator('canvas').waitFor({timeout:20000});
 assert.equal(await stage.getAttribute('data-doors'),'1','Explicit conceptual door is rendered only in chosen arch');
 await page.screenshot({path:'qa-v17-porch-infill-concept-mobile.png',fullPage:true});
 const source=await stage.getAttribute('data-photo-id');
 const project=await stage.getAttribute('data-project-id');
 assert.ok(source&&project);
 const first=await page.locator('.v17-trace-path').first().getAttribute('d');
 const handle=page.locator('.v17-trace-handle').first();
 const b=await handle.boundingBox();
 assert.ok(b);
 await page.mouse.move(b.x+b.width/2,b.y+b.height/2);
 await page.mouse.down();
 await page.mouse.move(b.x+b.width/2+14,b.y+b.height/2+5,{steps:4});
 await page.mouse.up();
 await stage.locator('canvas').waitFor({timeout:20000});
 assert.notEqual(await page.locator('.v17-trace-path').first().getAttribute('d'),first,'Arch geometry remains adjustable with active 3D view');
 assert.equal(await stage.getAttribute('data-project-id'),project,'Only this project can own the rebuilt preview');
 await page.locator('[data-v17-tab="design"]').click();
 await page.locator('[data-v17-tab="trace"]').click();
 await stage.locator('canvas').waitFor({timeout:20000});
 assert.equal(await stage.getAttribute('data-doors'),'1','Conceptual door persists across studio tabs');
 await page.goto('http://127.0.0.1:8765/',{waitUntil:'domcontentloaded'});
 await page.locator('[data-a="newphoto"]').click();
 await page.locator('a[href$="/studio"]').click();
 await page.locator('[data-v17-tab="trace"]').click();
 await page.getByText('No hay fotografías de esta propiedad disponibles aquí.').waitFor();
 assert.equal(await page.locator('#v17-porch-infill-3d canvas').count(),0,'Second house cannot reuse first house model');
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+5),true,'No mobile overflow');
 assert.deepEqual(errors,[],JSON.stringify(errors));
 console.log('PASS Porch Infill 3D mobile: project-specific arch shapes, explicit door, interactive redraw, tab teardown, separate house');
}finally{await browser.close();}
