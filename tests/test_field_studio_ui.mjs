import vm from 'node:vm';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const ctx={window:{},Math,JSON,Date};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(new URL('../js/field-studio-ui.js',import.meta.url),'utf8'),ctx);
const F=ctx.window.GSSFieldUI;
const project={id:'house-123',address:'22743 SW 56th Ave, Boca Raton',client:{name:'Example'},kind:'field',quote:{rate:0},fieldType:'porch'};
const other={id:'house-456',address:'Example other house'};
assert.equal(F.stages.length,7);
assert.match(F.introHome(),/assets\/gorilla-logo\.png/,'Real project branding, not invented text logo');
assert.match(F.homeStart(),/Nueva visita/);
assert.match(F.client(project),/aria-pressed="true"/);
assert.match(F.header(project,'aerea'),/PASO 3 DE 7/);
assert.match(F.bottom(project,'studio'),/href="#\/p\/house-123\/studio"/);
assert.equal((F.bottom(project,'fotos').match(/<a /g)||[]).length,5,'Five visible dock actions; no seven-item overcrowding');
assert.doesNotMatch(F.bottom(project,'studio'),/house-456/);
assert.match(F.more(project,'studio'),/data-fs-go="medidas"/);
const photosA=[{id:'a1',projectId:project.id,cat:'frente',url:'blob:real-house-a'}];
const photoGuide=F.photoGuide(project,photosA);
assert.match(photoGuide,/1\/6/);
assert.match(photoGuide,/blob:real-house-a/);
assert.match(photoGuide,/data-guide-cat="aerea"/);
assert.doesNotMatch(photoGuide,/real-house-b/,'No cross-project image reference');
const links={sat:'https://www.google.com/maps/search/?api=1&query=example',embed:'https://maps.google.com/maps?q=example',street:'#'};
assert.match(F.aerial(project,photosA,links),/No se guarda automáticamente/);
assert.match(F.analysis(project,photosA),/Ir a analizar fotografías/,'No invented AI success');
assert.match(F.studio(project,photosA),/La casa es la referencia/);
const deliver=F.deliverables(project,photosA,false,false);
for(const id of ['G-0','S-1','S-2','S-3'])assert.ok(deliver.includes(id),'Conceptual sheet '+id);
assert.match(deliver,/primero verifica y aprueba/);
assert.match(deliver,/No son planos sellados/);
assert.doesNotMatch(deliver,/\$2,216|approval|certified/,'No invented quote or engineering approval');
const app=fs.readFileSync(new URL('../js/app.js',import.meta.url),'utf8');
const index=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
const cache=fs.readFileSync(new URL('../sw.js',import.meta.url),'utf8');
assert.ok(app.includes('function tabAerea('));
assert.ok(app.includes('function tabAnalisis('));
assert.ok(app.includes('FS.studio('));
assert.ok(index.indexOf('js/field-studio-ui.js')<index.indexOf('js/app.js'));
assert.ok(cache.includes('field-studio.css'));
console.log('PASS Field Studio contract: real logos, seven-step seller flow, five-action dock, genuine project photos, no invented geometry/prices');
