import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const ctx={window:{},Math,Date,Number,String,Array,JSON};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(new URL('../js/porch-trace.js',import.meta.url),'utf8'),ctx);
const T=ctx.window.GSSPorchTrace;
const arch={id:'arch-1',label:'Arco izquierdo',left:210,right:405,top:280,spring:480,bottom:835,crown:315,measuredWidthFt:999,structuralSuitability:'approved'};
const projectA={id:'house-a',porchTrace:{schemaVersion:1,projectId:'house-a',photoId:'photo-a',arches:[arch],verified:true}};
const photosA=[{id:'photo-a',projectId:'house-a',url:'blob:example'}];
const original=JSON.stringify(projectA);
const draft=T.read(projectA,photosA);
assert.equal(draft.projectId,'house-a');
assert.equal(draft.photoId,'photo-a');
assert.equal(draft.arches.length,1);
assert.equal(draft.arches[0].left,210);
assert.equal(draft.arches[0].measurementStatus,'unverified');
assert.equal(draft.arches[0].structuralSuitability,'unverified');
assert.equal(draft.arches[0].measuredWidthFt,undefined,'AI-invented dimensions cannot enter trace data');
assert.equal(draft.verified,false,'Old approval flags cannot turn photo traces into verified measurements');
assert.equal(JSON.stringify(projectA),original,'Reading a draft never mutates existing designs');
assert.equal(T.read({id:'house-b',porchTrace:projectA.porchTrace},[{id:'photo-a',projectId:'house-b'}]),null);
assert.equal(T.read(projectA,[{id:'photo-a',projectId:'house-b'}]),null);
assert.equal(T.read(projectA,[]),null);
assert.equal(T.cleanArch({left:500,right:450,top:280,spring:480,bottom:800},0),null);
assert.equal(T.cleanArch({left:200,right:400,top:550,spring:480,bottom:800},0),null);
assert.match(T.path(draft.arches[0]),/^M210,835 L210,480 Q210,280/);
const app=fs.readFileSync(new URL('../js/app.js',import.meta.url),'utf8');
assert.ok(app.includes('p.porchTrace.projectId=p.id'),'Backup import must remap trace ownership');
assert.ok(app.includes('delete p.porchTrace;'),'Customer share links must exclude draft outlines');
const studio=fs.readFileSync(new URL('../js/v17-studio.js',import.meta.url),'utf8');
assert.ok(studio.includes("['trace','⌒','Porch Trace']"),'Studio must expose the trace editor in its navigation');
console.log('PASS Porch Trace: same-project photo ownership, unverified visual outlines, no inferred dimensions, safe backup and share');
