import vm from 'node:vm';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const env={window:{},Math,Date,JSON,Number,Array,Object,Set,Map,String};
vm.createContext(env);
vm.runInContext(fs.readFileSync(new URL('../js/v17-engine.js',import.meta.url),'utf8'),env);
const E=env.window.GSSV17Engine;
const s=E.defaults();
assert.equal(s.finish,'white');
assert.equal(s.postProfile,'2x5');
assert.equal(s.beamProfile,'2x8');
assert.equal(s.crossProfile,'2x2');
assert.equal(s.topRoofProfile,'2x2');
assert.equal(s.topWallProfile,'1x2');
assert.equal(s.chairHeight,3);
assert.equal(s.doorWidth,3);
assert.equal(s.waste,10);
assert.equal(s.verified,false);
s.width=30;s.depth=20;s.height=8;
let g=E.geometry(s);
assert.equal(g.frontBays,5);
assert.equal(g.sideBays,4);
assert.equal(g.postCount,14);
assert.equal(g.roofRows,4);
let segments=E.segments(s);
assert.equal(segments.filter(x=>x.profile==='2x8'&&x.use.startsWith('Primary big')).length,6);
assert.equal(segments.filter(x=>x.use.includes('Upper roof spline')).length,3);
assert.equal(segments.filter(x=>x.use.includes('Lower wall spline')).length,3);
assert.equal(segments.find(x=>x.use.includes('Bottom track')&&x.use.includes('front')).length,27);
assert.equal(segments.filter(x=>x.use==='Door jambs').length,2);
let report=E.takeoff(s);
assert.ok(report.meshSqft>g.wallArea);
assert.ok(report.rows.find(x=>x.profile==='2x2'));
assert.ok(report.rows.find(x=>x.profile==='1x2'));
assert.ok(report.rows.find(x=>x.profile==='2x8'));
assert.equal(E.price(s,report),null,'No invented price when supplier costs are missing');
let cuts=E.optimize([{length:24,use:'a',profile:'2x2'},{length:6,use:'b',profile:'2x2'}],[24,30],10);
assert.equal(cuts.used,30);assert.equal(cuts.purchased,48);
assert.equal(cuts.reserves,0,'Do not add waste twice over the offcut');
assert.equal(cuts.unresolved.length,0);
cuts=E.optimize([{length:31,use:'unspliced',profile:'2x8'}],[24,30],10);
assert.equal(cuts.unresolved.length,1);
const p={id:'project-a',openings:[],topScreen:{},gutter:{}};
assert.equal(E.orderStatus(s,p),'DRAFT');
s.verified=true;s.approvedOrder={signature:E.signature(s,p),approvedAt:Date.now()};
assert.equal(E.orderStatus(s,p),'APPROVED');
s.width=31;
assert.equal(E.orderStatus(s,p),'OUTDATED');
const b=E.defaults();assert.equal(b.width,0);assert.equal(b.depth,0);
const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
assert.ok(html.indexOf('js/v17-engine.js')<html.indexOf('js/v17-studio.js'));
assert.ok(html.indexOf('js/v17-studio.js')<html.indexOf('js/app.js'));
const app=fs.readFileSync(new URL('../js/app.js',import.meta.url),'utf8');
assert.ok(app.includes("['studio', 'Studio']"));
assert.ok(app.includes('function tabStudio(el)'));
console.log('PASS: V17 defaults, parametrics, wall/roof separation, optimized cuts, human approval, no fake prices, app integration');
